/**
 * @file prerender-seo.ts
 * @description Build-time SEO page generation. Runs automatically after
 * `npm run build` (the `postbuild` script) and turns the single-page dist/
 * into a set of crawler-ready static entry points:
 *
 *   dist/index.html                 <- home, rewritten in place
 *   dist/menu/index.html            <- one per public + legal page
 *   dist/stores/<slug>/index.html   <- one per PUBLISHED store (LocalBusiness JSON-LD)
 *   dist/careers/<slug>/index.html  <- one per PUBLISHED vacancy (JobPosting)
 *   dist/news/<slug>/index.html     <- one per PUBLISHED news post (NewsArticle)
 *   dist/sitemap.xml
 *   dist/robots.txt
 *   dist/seo-manifest.json          <- safe content hash + counts (no secrets)
 *
 * Each generated page is a copy of the built app shell with the <head>
 * rewritten: unique <title>, meta description, canonical URL, Open Graph +
 * Twitter cards (with an ABSOLUTE og:image) and JSON-LD structured data.
 * Link-preview crawlers (WhatsApp, iMessage, Facebook, Slack…) do not run
 * JavaScript, so this static head is what they see; Google additionally
 * renders the app itself for body content.
 *
 * SOURCE OF TRUTH (OPT-02-C1.2): **Supabase is the production source**. This
 * script no longer imports DEFAULT_SITE_CONTENT / INITIAL_* seed modules — it
 * receives a validated PublicContentSnapshot from scripts/load-public-content.ts
 * (production reads Supabase and FAILS CLOSED; development may fall back to the
 * bundled seeds, clearly stamped source: 'development-defaults'). The pages,
 * the sitemap and the JSON-LD are all derived from the SAME filtered snapshot,
 * and the manifest records the one canonical content hash so static crawler
 * output can be proven equal to the live database (see scripts/seo-live-parity).
 *
 * SITE_URL env var overrides the canonical origin (default milkpop.uk).
 */

